//
//  WHAT SUMMERLIN IS
//  · A master-planned community developed by Howard Hughes, spanning 22,500
//    acres along the western edge of the Las Vegas Valley. (Howard Hughes,
//    communities.howardhughes.com/regions/nevada.) Summerlin's own history page
//    describes the community as covering "nearly 36 square miles" — consistent,
//    since 22,500 acres is about 35 sq mi.
//  · Not a city. Not a Clark County town. Not a census place. There is no
//    government boundary that means "Summerlin."
//  · Howard Hughes puts current population at 132,000 residents and says about
//    5,000 gross acres remain reserved for future growth — the developer's own
//    figures, and the acreage explicitly includes infrastructure, open space and
//    common areas rather than only future rooftops. NOTE: summerlin.com's
//    history page gives "approximately 2,000 gross acres left to develop" as of
//    2023. The two do not reconcile and we do not know why, so the page uses the
//    5,000 figure with attribution and does not present it as settled.
//
//  ORIGIN & TIMELINE (summerlin.com/about/history, City of Las Vegas)
//  · 1952 — Howard Robard Hughes, Jr. acquires a 30,000-acre parcel on the
//    western rim of the valley for a reported $3 an acre.
//  · 1988 — Summa announces plans for Summerlin, named for Jean Amelia
//    Summerlin, Hughes's paternal grandmother. Land exchange with the BLM: Summa
//    gives up 5,000 acres of environmentally sensitive land for 3,000 acres more
//    appropriate for development.
//  · 1990 — development commences with the first village, The Hills, a 394-acre
//    residential village.
//  · 2002 — second exchange: about 1,000 acres of highlands to the BLM for about
//    1,000 acres along Summerlin's southernmost edge. THIS is why The Cliffs and
//    The Mesa sit south of Russell Road.
//  · 2014 — Downtown Summerlin opens.
//  · 2026 — 36th year of development.
//
//  JURISDICTION (City of Las Vegas Summerlin Development Standards, adopted
//  15 Sep 2004, revised 13 Oct 2025, case 25-0498-MOD1; Clark County
//  Comprehensive Planning)
//  · Summerlin is a PC (Planned Community) zoning district of the City of Las
//    Vegas. It was originally proposed as "Husite"; the City adopted a Master
//    Concept Plan and Land Use Plan on 6 May 1987 and annexed the land on
//    24 November 1989.
//  · 7 February 1997 — the City Council approved a development agreement,
//    annexation and reclassification of an additional 8,318 acres "known as the
//    Summerlin West area."
//  · Summerlin South is a Clark County land-use planning area of approximately
//    7,099 acres, "generally bounded by Charleston Boulevard on the north,
//    Russell Road on the south, Hualapai Way on the east, and the Red Rock
//    National Conservation Area on the west." Its Land Use and Development Guide
//    was approved 21 June 1995 and updated 22 June 2005. There is also a
//    Summerlin South census-designated place, which is a different thing again.
//  · The Development Standards write rules specifically for "areas west of the
//    215 Beltway" — the same line locals use for Summerlin West.
//
//  HIERARCHY (Summerlin Development Standards §1 and §5)
//  · Land use districts across the community: Neighborhood Residential,
//    Neighborhood Focus, Village Center, Town Center, Employment Center,
//    Community Open Space.
//  · Process: the master developer prepares a General Development Plan for one
//    or more VILLAGES, then Development Plans setting land use and density for
//    PARCELS inside them; builders then build NEIGHBORHOODS on those parcels.
//    Summerlin -> village -> parcel -> builder neighborhood. The planning
//    documents refer to villages by number (27, 28A/B, 29, 30A/B, 31, 32A/B/C).
//
//  ZIP CODES (summerlin.com/summerlin-defined-by-boundaries-not-zip-codes)
//  · Summerlin's own words: "It's important for buyers to understand our
//    community is defined by our official boundaries, not by zip code."
//  · Most often associated: 89134, 89135, 89138, 89144. The community also
//    extends into 89148. Several Summerlin neighborhoods (Terra Luna, Jade
//    Ridge, Onyx Point) sit outside the usual four but inside the boundaries.
//  · Red Rock Country Club is "not technically part of the Summerlin master
//    plan" (summerlin.com) — the cleanest example of near-Summerlin-but-not-in-it.
//
//  VILLAGE FIGURES (all summerlin.com)
//  · The Arbors 1,206 ac · The Ridges 793 ac · The Paseos 768 ac · The Canyons
//    754 ac · The Willows 731 ac · The Trails 573 ac · The Cliffs just over
//    418 ac (Summerlin's southernmost village, nine neighborhoods) · The Hills
//    394 ac (the first).
//  · The Ridges sits at about 4,000 ft, is guard-gated, and is built around
//    Bear's Best, a Jack Nicklaus course. Kestrel is "perched above the valley at
//    over 3,000 feet."
//  · Astra, a custom homesite enclave at the base of the La Madre Peaks
//    mountains, debuted 2025: 167 homesites across 171 acres.
//
//  AMENITIES (summerlin.com)
//  · More than 300 parks; nearly 40 major community parks ranging from 5 to
//    90 acres. 200-plus miles of interconnected trails, planned to eventually
//    exceed 250. Ten golf courses. 26 public, private and charter schools.
//    NOTE: the school COUNT is a fact; the page makes no claim about school
//    quality or ranking anywhere.
//  · "Six distinct villages and districts" in Summerlin's own recent copy refers
//    to the villages ACTIVELY SELLING, not the total. Do not turn it into a
//    village count. Summerlin does not publish a running total, so neither do we.
//
//  DOWNTOWN SUMMERLIN
//  · The greater Downtown Summerlin area is 400 acres and lies within the
//    community of Summerlin South. The open-air center inside it is 106 acres
//    and 1.6 million sq ft, with more than 125 shops, bars and restaurants,
//    anchored by Dillard's and Macy's. Grand opening 9 October 2014.
//  · Bounded by Charleston Blvd (N), Sahara Ave (S), the 215 (W), Town Center
//    Drive (E).
//  · Las Vegas Ballpark opened 2019 (Las Vegas Aviators, Triple-A). City
//    National Arena opened 2017 (Vegas Golden Knights practice facility and HQ,
//    plus UNLV hockey). Red Rock Resort opened April 2006.
//  · Offices: City National Bank Building (2007), One Summerlin (April 2015),
//    Two Summerlin (August 2018), 1700 Pavilion (2022), Meridian (2025).
//
//  RED ROCK CANYON (BLM)
//  · Designated a National Conservation Area in 1990 — the seventh nationally
//    and the first in Nevada. 13-mile scenic drive. More than three million
//    visitors a year. Timed-entry reservations required for the scenic drive
//    1 October - 31 May, 8am-5pm.
//
//  PRICING
//  · No "average Summerlin home price" is published on this page. Summerlin
//    spans 22,500 acres, from age-restricted condos to guard-gated custom
//    homesites, and any single median depends entirely on what the person
//    calculating it decided to include. The valley-wide LVR figure lives on the
//    market-watch guide.
//
//  FAIR HOUSING
//  · No school ratings, no crime or safety claims, no demographic
//    characterization of residents, no "great for families"-style steering
//    anywhere on this page. Fit is expressed through housing stock, geography
//    and daily logistics only.
//  · Sun City Summerlin and the "Active Adult" villages are described as
//    age-restricted HOUSING — that is the legal designation of the product
//    itself, not a suggestion about who should live where.
